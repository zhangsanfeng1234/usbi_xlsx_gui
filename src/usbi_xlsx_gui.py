    def _log(self, message):
        self.events.put(("log", message))

    def _poll(self):
        try:
            while True:
                event, value = self.events.get_nowait()
                if event == "log":
                    self.log_box.configure(state="normal")
                    self.log_box.insert("end", value + "\n")
                    self.log_box.see("end")
                    self.log_box.configure(state="disabled")
                elif event == "single_done":
                    self.busy = False
                    output, count = value
                    self.last_output = Path(output)
                    self.open_button.configure(state="normal")
                    self.run_button.configure(state="normal")
                    from tkinter import messagebox
                    messagebox.showinfo(
                        "生成完成",
                        f"Excel 已生成：\n{output}\n\n清单记录：{count} 条",
                    )
                elif event == "compare_done":
                    self.busy = False
                    output, added, missing, changed = value
                    self.last_output = Path(output)
                    self.open_button.configure(state="normal")
                    self.run_button.configure(state="normal")
                    from tkinter import messagebox
                    messagebox.showinfo(
                        "对比完成",
                        f"Excel 已生成：\n{output}\n\n新增：{added} 条\n缺少：{missing} 条\n差异：{changed} 条",
                    )
                elif event == "error":
                    self.busy = False
                    self.last_output = None
                    self.open_button.configure(state="disabled")
                    self.run_button.configure(state="normal")
                    from tkinter import messagebox
                    messagebox.showerror("处理失败", value)
        except queue.Empty:
            pass
        self.root.after(100, self._poll)

