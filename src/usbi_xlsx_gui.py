ROOT = Path(__file__).resolve().parent
PROJECT_ROOT = ROOT.parent
# Excel formatting is generated by code so the packaged EXE does not depend on
# an external 工作簿1.xlsx file. A custom template can still be selected manually.
FROZEN_ROOT = Path(sys.executable).resolve().parent if getattr(sys, "frozen", False) else ROOT
BUNDLE_ROOT = Path(getattr(sys, "_MEIPASS", ROOT))
DEFAULT_TEMPLATE_NAME = "工作簿1.xlsx"
DEFAULT_HEADERS = ["文件名称", "版本号", "路径", "MD5值", "备注"]
METADATA_FILE_NAMES = frozenset({"checksums.txt", ".gitkeep"})
GREEN_FILL = "FF92D050"
YELLOW_FILL = "FFFFFF00"


def md5_file(path: Path) -> str:
    digest = hashlib.md5()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest().upper()


def version_from_path(source: Path) -> str:
    text = str(source.parent.parent if source.parent.name.upper() == "IFT" else source.parent)
    match = re.search(r"(V\d+(?:\.\d+)*)", text, re.IGNORECASE)
    return match.group(1).upper() if match else "V1.0"


def _normalise_manifest_path(value: str | None) -> str:
    """Normalize an Excel manifest path so slash/case differences do not matter."""
    text = str(value or "").strip().replace("/", "\\")
    text = re.sub(r"\\+", lambda _match: "\\", text).strip("\\")
    return text.casefold()


def default_template_path(source: Path | None = None, output_dir: Path | None = None) -> Path | None:
    """Find the bundled/default workbook without requiring a template argument."""
    roots: list[Path] = [
        FROZEN_ROOT,
        PROJECT_ROOT,
        ROOT,
        BUNDLE_ROOT,
        BUNDLE_ROOT.parent,
    ]
    if source:
        roots.append(source.expanduser().parent)
    if output_dir:
        roots.append(output_dir.expanduser())
    roots.append(Path.cwd())

    seen: set[str] = set()
    for root in roots:
        candidate = (root / DEFAULT_TEMPLATE_NAME).expanduser()
        key = str(candidate).casefold()
        if key in seen:
            continue
        seen.add(key)
        if candidate.is_file():
            return candidate.resolve()
    return None


def _is_metadata_file(relative: Path) -> bool:
    return relative.name.casefold() in METADATA_FILE_NAMES


def _template_fill_kind(cell) -> str | None:
    """Return the workbook's semantic fill name for a template cell."""
    if cell.fill.fill_type != "solid":
        return None
    color = cell.fill.fgColor
    if color.type == "rgb" and color.rgb:
        rgb = color.rgb.upper()
        if rgb.endswith(GREEN_FILL[-6:]):
            return "green"
        if rgb.endswith(YELLOW_FILL[-6:]):
            return "yellow"
    return None


def embedded_payload(source: Path) -> bytes:
    """Return the decompressed payload from a self-extracting archive."""
    data = source.read_bytes()
    errors: list[str] = []

    # Most usbi.sh files have a shell header followed by bzip2 data.
    candidates: list[tuple[str, int]] = []
    for magic, label in ((b"BZh", "bzip2"), (b"\x1f\x8b", "gzip"), (b"PK\x03\x04", "zip")):
        offset = data.find(magic)
        if offset >= 0:
            candidates.append((label, offset))
    # A plain tar may have no recognizable magic at the beginning, but its ustar marker is fixed.
    candidates.append(("tar", 0))

    for label, offset in candidates:
        blob = data[offset:]
        try:
            if label == "bzip2":
                return bz2.decompress(blob)
            if label == "gzip":
                return gzip.decompress(blob)
            if label == "zip":
                # zip is returned as-is and handled by extract_archive.
                return blob
            if label == "tar" and (len(blob) >= 265 and blob[257:262] in (b"ustar", b"ustar ")):
                return blob
        except Exception as exc:  # try the next possible embedded stream
            errors.append(f"{label}: {exc}")

    detail = "; ".join(errors)
    raise ValueError("无法识别 usbi.sh 中的压缩数据。" + (f" 详细信息：{detail}" if detail else ""))


def _safe_target(root: Path, member_name: str) -> Path:
    # Tar names are POSIX paths. Reject traversal and absolute paths.
    name = member_name.replace("\\", "/")
    target = (root / Path(name)).resolve()
    root_resolved = root.resolve()
    try:
        target.relative_to(root_resolved)
    except ValueError as exc:
        raise ValueError(f"归档包含越界路径，已拒绝：{member_name}") from exc
    return target


def extract_tar_bytes(payload: bytes, destination: Path, log: Callable[[str], None] | None = None) -> int:
    destination.mkdir(parents=True, exist_ok=True)
    extracted = 0
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:") as archive:
        for member in archive:
            target = _safe_target(destination, member.name)
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            if member.isfile():
                target.parent.mkdir(parents=True, exist_ok=True)
                source = archive.extractfile(member)
                if source is None:
                    continue
                with target.open("wb") as out:
                    shutil.copyfileobj(source, out, length=1024 * 1024)
                extracted += 1
                continue
            # A symlink is not needed for the manifest and can be unsafe/unreliable on Windows.
            if log:
                log(f"跳过非普通文件：{member.name}")
    return extracted


def extract_zip_bytes(payload: bytes, destination: Path) -> int:
    destination.mkdir(parents=True, exist_ok=True)
    extracted = 0
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        for info in archive.infolist():
            target = _safe_target(destination, info.filename)
            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(info) as source, target.open("wb") as out:
                shutil.copyfileobj(source, out, length=1024 * 1024)
            extracted += 1
    return extracted


def extract_archive(source: Path, destination: Path, log: Callable[[str], None] | None = None) -> int:
    payload = embedded_payload(source)
    if payload[:2] == b"PK":
        return extract_zip_bytes(payload, destination)
    if len(payload) >= 265 and payload[257:262] in (b"ustar", b"ustar "):
        return extract_tar_bytes(payload, destination, log)
    # Some packages contain a second compression layer.
    if payload[:3] == b"BZh":
        return extract_tar_bytes(bz2.decompress(payload), destination, log)
    if payload[:2] == b"\x1f\x8b":
        return extract_tar_bytes(gzip.decompress(payload), destination, log)
    raise ValueError("已找到压缩数据，但解压结果不是 TAR/ZIP 文件。")


def iter_regular_files(root: Path) -> Iterable[Path]:
    for path in root.rglob("*"):
        if path.is_file() and not path.is_symlink():
            yield path


def collect_records(extracted_root: Path, version: str, include_metadata: bool = True,
                    log: Callable[[str], None] | None = None) -> list[tuple[str, str, str, str, str]]:
    records = []
    for path in sorted(iter_regular_files(extracted_root), key=lambda p: p.relative_to(extracted_root).as_posix().lower()):
        relative = path.relative_to(extracted_root)
        # checksums.txt and .gitkeep are package metadata/placeholders. They
        # remain included by default so the manifest reflects every ordinary
        # extracted file; --no-metadata can omit them when cleanup is desired.
        if not include_metadata and _is_metadata_file(relative):
            if log:
                log(f"跳过多余元数据文件：{relative.as_posix()}")
            continue
        parent = relative.parent.as_posix()
        excel_path = "update" if parent == "." else "update\\" + parent.replace("/", "\\")
        digest = md5_file(path)
        records.append((relative.name, version, excel_path, digest, ""))
        if log:
            log(f"MD5 {digest}  {relative.as_posix()}")
    return records


def _style_for_path(path_value: str) -> str:
    """Classify a manifest directory using the template's path conventions.

    The template contains examples for the known firmware tree.  The rules
    deliberately operate on normalized path components, so archives using
    forward slashes, different case, or a newly named directory still get an
    appropriate style and fill color.  More specific paths are checked before
    broad suffixes (for example ``lib\\firmware`` before ``\\firmware``).
    """
    p = _normalise_manifest_path(path_value)
    if p.endswith("\\lib\\firmware"):
        return "firmware_lib"
    if p.endswith("\\lib\\hal_lib64"):
        return "hal_lib64"
    if p.endswith("\\lib\\hal_lib"):
        return "hal_lib"
    if p.endswith("\\usr\\lib\\systemd\\system"):
        return "usr_lib"
    if p.endswith("\\lib\\systemd\\system"):
        return "systemd"
    if p in {"update", "update\\firmware"} or p.endswith("\\firmware"):
        return "firmware"
    if p.endswith("\\rootfs\\bin"):
        return "bin"
    if "\\custom\\sys\\bin64" in p:
        return "scripts"
    if "\\data\\" in f"\\{p}\\" or p.endswith("\\data"):
        return "data"
    if p.endswith("\\rootfs\\etc") or "\\etc\\" in f"\\{p}\\" or p.endswith("\\udev\\rules.d"):
        return "etc"
    if "\\modules\\" in f"\\{p}\\":
        if p.endswith("\\extra"):
            return "modules_extra"
        if "\\drivers\\net\\can\\" in f"\\{p}\\":
            return "modules_can"
        if "\\drivers\\usb\\dwc3" in f"\\{p}\\":
            return "modules_dwc3"
        if "\\drivers\\usb\\serial" in f"\\{p}\\":
            return "modules_serial"
        if "\\drivers\\usb\\sunxi_usb" in f"\\{p}\\":
            return "modules_sunxi_usb"
    if p.endswith("\\mnt\\internal_storage"):
        return "internal"
    if p.endswith("\\sbin"):
        return "sbin"
    if p.endswith("\\usr\\local\\extapps"):
        return "extapps"
    if p == "update\\toolkit" or p.endswith("\\toolkit"):
        return "toolkit"
    # New configuration-like directories are treated like the template's
    # yellow data rows; unknown executable/system directories remain green.
    if any(marker in f"\\{p}\\" for marker in ("\\config\\", "\\cfg\\", "\\download\\", "\\history\\")):
        return "data"
    return "firmware"


def _fill_kind_for_path(path_value: str) -> str:
    return "yellow" if _style_for_path(path_value) in {
        "bin", "data", "hal_lib", "modules_extra", "modules_dwc3",
        "modules_sunxi_usb", "internal", "toolkit",
    } else "green"


def _manifest_workbook_from_template(template: Path | None):
    """Create a workbook and collect reusable manifest row styles."""
    if template:
        template = template.expanduser().resolve()
        wb = load_workbook(template)
        ws = wb.active
        style_by_path: dict[str, tuple] = {}
        style_by_kind: dict[str, tuple] = {}
        style_by_fill: dict[str, tuple] = {}
        fill_by_kind: dict[str, tuple] = {}

        for row in range(2, ws.max_row + 1):
            path_value = ws.cell(row, 3).value
            if not isinstance(path_value, str) or not path_value.strip():
                continue
            styles = tuple(copy(ws.cell(row, col)._style) for col in range(1, 6))
            normalized_path = _normalise_manifest_path(path_value)
            style_by_path.setdefault(normalized_path, styles)
            style_by_kind.setdefault(_style_for_path(path_value), styles)
            fill_kind = _template_fill_kind(ws.cell(row, 1))
            if fill_kind:
                style_by_fill.setdefault(fill_kind, styles)
                fill_by_kind.setdefault(
                    fill_kind,
                    tuple(copy(ws.cell(row, col).fill) for col in range(1, 6)),
                )

        if ws.max_row > 1:
            ws.delete_rows(2, ws.max_row - 1)
    else:
        wb = Workbook()
        ws = wb.active
        ws.title = "Sheet1"
        for col, value in enumerate(DEFAULT_HEADERS, 1):
            cell = ws.cell(1, col, value)
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="4472C4")
            cell.alignment = Alignment(horizontal="center", vertical="center")
            cell.border = Border(bottom=Side(style="thin", color="808080"))
        ws.row_dimensions[1].height = 21
        for col, width in {"A": 34, "B": 14, "C": 62, "D": 36, "E": 24}.items():
            ws.column_dimensions[col].width = width

        # Build two generic row styles only for the fallback case where the
        # default template is unavailable.
        style_by_path = {}
        style_by_kind = {}
        style_by_fill = {}
        fill_by_kind = {}
        for fill_kind, color in (("green", GREEN_FILL), ("yellow", YELLOW_FILL)):
            sample_styles = []
            sample_fills = []
            for col in range(1, 6):
                cell = ws.cell(2, col)
                cell.font = Font(name="Consolas" if col == 1 or col == 4 else "Arial", size=10)
                cell.fill = PatternFill("solid", fgColor=color) if col < 5 else PatternFill()
                cell.alignment = Alignment(
                    horizontal="center" if col == 2 else "left",
                    vertical="center",
                )
                cell.border = Border(
                    left=Side(style="thin", color="D9DEE7"),
                    right=Side(style="thin", color="D9DEE7"),
                    top=Side(style="thin", color="D9DEE7"),
                    bottom=Side(style="thin", color="D9DEE7"),
                )
                sample_styles.append(copy(cell._style))
                sample_fills.append(copy(cell.fill))
            style_by_kind["firmware" if fill_kind == "green" else "data"] = tuple(sample_styles)
            style_by_fill[fill_kind] = tuple(sample_styles)
            fill_by_kind[fill_kind] = tuple(sample_fills)
        ws.delete_rows(2, 1)

    return wb, ws, style_by_path, style_by_kind, style_by_fill, fill_by_kind


def _copy_manifest_layout(source_ws, target_ws) -> None:
    """Copy the visible manifest header and column layout to another sheet."""
    for col in range(1, 6):
        letter = openpyxl.utils.get_column_letter(col)
        target_ws.column_dimensions[letter].width = source_ws.column_dimensions[letter].width
        src = source_ws.cell(1, col)
        dst = target_ws.cell(1, col, src.value if src.value is not None else DEFAULT_HEADERS[col - 1])
        if src.has_style:
            dst._style = copy(src._style)
        dst.alignment = copy(src.alignment)
    target_ws.row_dimensions[1].height = source_ws.row_dimensions[1].height


def _write_manifest_sheet(ws, records: list[tuple[str, str, str, str, str]],
                          style_by_path: dict[str, tuple], style_by_kind: dict[str, tuple],
                          style_by_fill: dict[str, tuple], fill_by_kind: dict[str, tuple]) -> None:
    """Write one file manifest sheet; background switches whenever path changes."""
    if ws.max_row > 1:
        ws.delete_rows(2, ws.max_row - 1)

    # Ensure headers exist even if a custom template has a blank header cell.
    for col, value in enumerate(DEFAULT_HEADERS, 1):
        if ws.cell(1, col).value is None:
            ws.cell(1, col, value)

    last_path_key: str | None = None
    current_fill_kind = "yellow"
    for row_num, record in enumerate(records, start=2):
        path_value = record[2]
        path_key = _normalise_manifest_path(path_value)
        if path_key != last_path_key:
            # Toggle fill when the file path changes. Files under the same path
            # keep the same background color; the next path switches color.
            current_fill_kind = "green" if current_fill_kind == "yellow" else "yellow"
            last_path_key = path_key
        style_kind = _style_for_path(path_value)
        fill_kind = current_fill_kind
        styles = (
            style_by_path.get(path_key)
            or style_by_kind.get(style_kind)
            or style_by_fill.get(fill_kind)
        )
        fills = fill_by_kind.get(fill_kind)
        for col, value in enumerate(record, start=1):
            cell = ws.cell(row_num, col, value=value if value != "" else None)
            if styles:
                cell._style = copy(styles[col - 1])
            # Explicitly replace only the fill.  This is what makes a path
            # outside the original sample rows visibly follow its category.
            if fills:
                cell.fill = copy(fills[col - 1])
            alignment = copy(cell.alignment)
            alignment.vertical = "center"
            alignment.wrap_text = False
            cell.alignment = alignment

    end_row = len(records) + 1
    ws.auto_filter.ref = f"A1:E{end_row}"
    ws.freeze_panes = "A2"
    ws.print_area = f"A1:E{end_row}"


def make_workbook(records: list[tuple[str, str, str, str, str]], output: Path,
                  template: Path | None = None) -> None:
    """Write a single-version manifest workbook."""
    wb, ws, style_by_path, style_by_kind, style_by_fill, fill_by_kind = _manifest_workbook_from_template(template)
    _write_manifest_sheet(ws, records, style_by_path, style_by_kind, style_by_fill, fill_by_kind)
    output.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output)


def _record_key(record: tuple[str, str, str, str, str]) -> str:
    """Compare records by file path + file name."""
    return f"{_normalise_manifest_path(record[2])}\\{str(record[0]).casefold()}"


def _record_sort_key(record: tuple[str, str, str, str, str]) -> tuple[str, str]:
    return (_normalise_manifest_path(record[2]), str(record[0]).casefold())


def compare_record_sets(baseline_records: list[tuple[str, str, str, str, str]],
                        compare_records: list[tuple[str, str, str, str, str]]):
    """Return added, missing and changed files from compare_records against baseline_records."""
    baseline_by_key = {_record_key(record): record for record in baseline_records}
    compare_by_key = {_record_key(record): record for record in compare_records}
    baseline_keys = set(baseline_by_key)
    compare_keys = set(compare_by_key)

    added = sorted((compare_by_key[key] for key in compare_keys - baseline_keys), key=_record_sort_key)
    missing = sorted((baseline_by_key[key] for key in baseline_keys - compare_keys), key=_record_sort_key)
    changed = []
    for key in baseline_keys & compare_keys:
        baseline = baseline_by_key[key]
        compared = compare_by_key[key]
        if baseline[3] != compared[3]:
            changed.append((baseline, compared))
    changed.sort(key=lambda pair: _record_sort_key(pair[0]))
    return added, missing, changed


def _write_compare_section(ws, start_row: int, title: str, fill_color: str,
                           rows: list[list[str]]) -> int:
    headers = ["文件名称", "文件路径", "基线MD5", "对比MD5", "说明"]
    label = ws.cell(start_row, 1, title)
    label.font = Font(bold=True, size=12)
    header_row = start_row + 1
    fill = PatternFill("solid", fgColor=fill_color)
    thin = Side(style="thin", color="D9DEE7")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    for col, header in enumerate(headers, start=1):
        cell = ws.cell(header_row, col, header)
        cell.font = Font(bold=True, color="FFFFFF" if fill_color == "FFFF0000" else "000000")
        cell.fill = fill
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = border

    if not rows:
        rows = [["无", "", "", "", ""]]

    for offset, values in enumerate(rows, start=1):
        row_num = header_row + offset
        for col, value in enumerate(values, start=1):
            cell = ws.cell(row_num, col, value if value != "" else None)
            cell.fill = fill
            cell.border = border
            cell.alignment = Alignment(vertical="center", wrap_text=False)
            if fill_color == "FFFF0000":
                cell.font = Font(color="FFFFFF")

    return header_row + len(rows) + 2


def make_comparison_workbook(baseline_records: list[tuple[str, str, str, str, str]],
                             compare_records: list[tuple[str, str, str, str, str]],
                             output: Path, template: Path | None = None) -> tuple[int, int, int]:
    """Write a three-sheet workbook: baseline, compared version, and comparison result."""
    wb, base_ws, style_by_path, style_by_kind, style_by_fill, fill_by_kind = _manifest_workbook_from_template(template)
    for sheet in list(wb.worksheets):
        if sheet is not base_ws:
            wb.remove(sheet)

    base_ws.title = "基线版本"
    _write_manifest_sheet(base_ws, baseline_records, style_by_path, style_by_kind, style_by_fill, fill_by_kind)

    compare_ws = wb.create_sheet("对比版本")
    _copy_manifest_layout(base_ws, compare_ws)
    _write_manifest_sheet(compare_ws, compare_records, style_by_path, style_by_kind, style_by_fill, fill_by_kind)

    added, missing, changed = compare_record_sets(baseline_records, compare_records)
    result_ws = wb.create_sheet("对比结果")
    for col, width in {"A": 30, "B": 62, "C": 36, "D": 36, "E": 20}.items():
        result_ws.column_dimensions[col].width = width
    result_ws.freeze_panes = "A3"

    added_rows = [[record[0], record[2], "", record[3], "新增"] for record in added]
    missing_rows = [[record[0], record[2], record[3], "", "缺少"] for record in missing]
    changed_rows = [[baseline[0], baseline[2], baseline[3], compared[3], "MD5不同"] for baseline, compared in changed]

    row = 1
    row = _write_compare_section(result_ws, row, "新增：", "FF00B0F0", added_rows)
    row = _write_compare_section(result_ws, row, "缺少：", "FFFFFF00", missing_rows)
    _write_compare_section(result_ws, row, "差异：", "FFFF0000", changed_rows)
    # The result sheet contains three independent sections, so one global
    # AutoFilter would be misleading; keep the sections visually grouped.
    result_ws.auto_filter.ref = None
    result_ws.print_area = f"A1:E{result_ws.max_row}"

    output.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output)
    return len(added), len(missing), len(changed)

def _next_output_path(source: Path, output_dir: Path, stamp: str) -> Path:
    """Keep the familiar timestamped name without overwriting an old report."""
    base = output_dir / f"{source.stem}_文件清单_{stamp}.xlsx"
    if not base.exists():
        return base
    index = 1
    while True:
        candidate = output_dir / f"{source.stem}_文件清单_{stamp}_{index:02d}.xlsx"
        if not candidate.exists():
            return candidate
        index += 1


def _remove_extraction_dir(extraction_dir: Path, output_dir: Path,
                          log: Callable[[str], None] | None = None) -> None:
    """Delete only a tool-created extraction directory below output_dir."""
    extraction_resolved = extraction_dir.resolve()
    output_resolved = output_dir.resolve()
    try:
        extraction_resolved.relative_to(output_resolved)
    except ValueError as exc:
        raise ValueError(f"拒绝删除输出目录之外的临时目录：{extraction_resolved}") from exc
    if not extraction_resolved.name.endswith("_extracted") and "_extracted_" not in extraction_resolved.name:
        raise ValueError(f"拒绝删除非工具生成的目录：{extraction_resolved}")
    shutil.rmtree(extraction_resolved)
    if log:
        log(f"已删除临时解压目录：{extraction_resolved}")


def _remove_metadata_files(extracted_root: Path,
                           log: Callable[[str], None] | None = None) -> int:
    removed = 0
    for path in sorted(extracted_root.rglob("*"), key=lambda item: len(item.parts), reverse=True):
        if path.is_file() and not path.is_symlink() and _is_metadata_file(path.relative_to(extracted_root)):
            path.unlink()
            removed += 1
    if removed and log:
        log(f"已删除多余元数据文件：{removed} 个（checksums.txt/.gitkeep）")
    return removed


def generate(source: Path, output_dir: Path, template: Path | None = None, version: str | None = None,
             keep_extracted: bool = False, include_metadata: bool = True,
             log: Callable[[str], None] | None = None) -> tuple[Path, Path, int]:
    source = source.expanduser().resolve()
    output_dir = output_dir.expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f"找不到输入文件：{source}")
    if source.suffix.lower() != ".sh" and log:
        log("提示：输入文件扩展名不是 .sh，仍继续尝试识别格式。")
    output_dir.mkdir(parents=True, exist_ok=True)
    version = (version or "").strip().upper() or version_from_path(source)
    if template:
        template = template.expanduser().resolve()
        if not template.is_file():
            raise FileNotFoundError(f"找不到 Excel 模板：{template}")

    stamp = time.strftime("%Y%m%d_%H%M%S")
    extraction_dir = output_dir / f"{source.stem}_extracted_{stamp}_{time.time_ns() % 1000000:06d}"
    output_xlsx = _next_output_path(source, output_dir, stamp)

    if log:
        log(f"输入：{source}")
        log(f"版本号：{version}")
        log(f"Excel 样式：{template if template else '内置自动样式'}")
        log("正在解压嵌套压缩包，请稍候……")

    try:
        count = extract_archive(source, extraction_dir, log)
        if log:
            log(f"解压完成：{count} 个普通文件")
            log("正在计算 MD5 并写入 Excel……")
        records = collect_records(extraction_dir, version, include_metadata, log)
        make_workbook(records, output_xlsx, template)
        if not include_metadata and keep_extracted:
            _remove_metadata_files(extraction_dir, log)
        if log:
            log(f"Excel 已生成：{output_xlsx}")
            log(f"清单记录：{len(records)} 条")
    finally:
        if not keep_extracted and extraction_dir.exists():
            try:
                _remove_extraction_dir(extraction_dir, output_dir, log)
            except Exception as exc:
                # Do not discard a valid Excel result just because Windows is
                # temporarily holding one extracted file open.
                if log:
                    log(f"警告：临时目录删除失败，请手动删除：{extraction_dir}（{exc}）")

    if log and keep_extracted:
        log(f"解压目录：{extraction_dir}")
    return output_xlsx, extraction_dir, len(records)



def _next_comparison_output_path(baseline_source: Path, compare_source: Path,
                                 output_dir: Path, stamp: str) -> Path:
    """Build a non-overwriting filename for a two-version comparison report."""
    def clean_stem(value: str) -> str:
        value = re.sub(r"[<>:\"/\\|?*]+", "_", value).strip(" .")
        return value or "usbi"

    baseline_name = clean_stem(baseline_source.stem)
    compare_name = clean_stem(compare_source.stem)
    base = output_dir / f"{baseline_name}_vs_{compare_name}_对比清单_{stamp}.xlsx"
    if not base.exists():
        return base
    index = 1
    while True:
        candidate = output_dir / f"{baseline_name}_vs_{compare_name}_对比清单_{stamp}_{index:02d}.xlsx"
        if not candidate.exists():
            return candidate
        index += 1


def generate_comparison(baseline_source: Path, compare_source: Path, output_dir: Path,
                        template: Path | None = None,
                        baseline_version: str | None = None,
                        compare_version: str | None = None,
                        keep_extracted: bool = False,
                        include_metadata: bool = True,
                        log: Callable[[str], None] | None = None) -> tuple[Path, int, int, int]:
    """Extract two archives and create a three-sheet comparison workbook."""
    baseline_source = baseline_source.expanduser().resolve()
    compare_source = compare_source.expanduser().resolve()
    output_dir = output_dir.expanduser().resolve()
    for label, source in (("基线版本", baseline_source), ("对比版本", compare_source)):
        if not source.is_file():
            raise FileNotFoundError(f"找不到{label}输入文件：{source}")
        if source.suffix.lower() != ".sh" and log:
            log(f"提示：{label}文件扩展名不是 .sh，仍继续尝试识别格式。")

    output_dir.mkdir(parents=True, exist_ok=True)
    baseline_version = (baseline_version or "").strip().upper() or version_from_path(baseline_source)
    compare_version = (compare_version or "").strip().upper() or version_from_path(compare_source)
    if template:
        template = template.expanduser().resolve()
        if not template.is_file():
            raise FileNotFoundError(f"找不到 Excel 模板：{template}")

    stamp = time.strftime("%Y%m%d_%H%M%S")
    unique = time.time_ns() % 1000000
    baseline_extraction = output_dir / f"{baseline_source.stem}_baseline_extracted_{stamp}_{unique:06d}"
    compare_extraction = output_dir / f"{compare_source.stem}_compare_extracted_{stamp}_{(unique + 1) % 1000000:06d}"
    output_xlsx = _next_comparison_output_path(baseline_source, compare_source, output_dir, stamp)

    if log:
        log(f"基线版本：{baseline_source}")
        log(f"基线版本号：{baseline_version}")
        log(f"对比版本：{compare_source}")
        log(f"对比版本号：{compare_version}")
        log(f"Excel 样式：{template if template else '内置自动样式'}")
        log("正在解压基线版本……")

    extraction_dirs = (baseline_extraction, compare_extraction)
    baseline_records: list[tuple[str, str, str, str, str]] = []
    compare_records: list[tuple[str, str, str, str, str]] = []
    try:
        baseline_count = extract_archive(baseline_source, baseline_extraction, log)
        if log:
            log(f"基线版本解压完成：{baseline_count} 个普通文件")
            log("正在解压对比版本……")
        compare_count = extract_archive(compare_source, compare_extraction, log)
        if log:
            log(f"对比版本解压完成：{compare_count} 个普通文件")
            log("正在分别计算 MD5 并执行文件对比……")
        baseline_records = collect_records(baseline_extraction, baseline_version, include_metadata, log)
        compare_records = collect_records(compare_extraction, compare_version, include_metadata, log)
        added_count, missing_count, changed_count = make_comparison_workbook(
            baseline_records, compare_records, output_xlsx, template
        )
        if log:
            log(f"对比 Excel 已生成：{output_xlsx}")
            log(f"基线记录：{len(baseline_records)} 条；对比记录：{len(compare_records)} 条")
            log(f"新增：{added_count} 条；缺少：{missing_count} 条；差异：{changed_count} 条")
    finally:
        if not keep_extracted:
            for extraction_dir in extraction_dirs:
                if extraction_dir.exists():
                    try:
                        _remove_extraction_dir(extraction_dir, output_dir, log)
                    except Exception as exc:
                        if log:
                            log(f"警告：临时目录删除失败，请手动删除：{extraction_dir}（{exc}）")
        elif not include_metadata:
            for extraction_dir in extraction_dirs:
                if extraction_dir.exists():
                    _remove_metadata_files(extraction_dir, log)

    if log and keep_extracted:
        log(f"基线解压目录：{baseline_extraction}")
        log(f"对比解压目录：{compare_extraction}")
    return output_xlsx, added_count, missing_count, changed_count



